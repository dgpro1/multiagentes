function escapeRegExp(value: string): string {
  return value.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
}

const COMPILED = API_ERROR_TEMPLATES_ES.map(([english, spanish]) => ({
  pattern: new RegExp(`^${english.split("{}").map(escapeRegExp).join("(.+?)")}$`, "s"),
  spanish,
}));

/** ``message`` in Spanish when the table knows it, otherwise as the API wrote it. */
export function apiErrorInSpanish(message: string): string {
  const exact = API_ERRORS_ES[message];
  if (exact) return exact;
  for (const { pattern, spanish } of COMPILED) {
    const match = pattern.exec(message);
    if (!match) continue;
    let index = 1;
    return spanish.replace(/\{\}/g, () => apiErrorInSpanish(match[index++] ?? ""));
  }
  return message;
}
